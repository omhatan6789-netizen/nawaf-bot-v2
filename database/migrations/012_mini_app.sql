CREATE TABLE IF NOT EXISTS mini_app_settings (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    banner_file_id TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO mini_app_settings(id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS mini_app_buttons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    target TEXT NOT NULL,
    button_type TEXT NOT NULL CHECK (button_type IN ('small','large')),
    color TEXT NOT NULL DEFAULT '#ffffff',
    image_file_id TEXT,
    button_order INTEGER NOT NULL DEFAULT 0,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_mini_app_buttons_order
    ON mini_app_buttons(button_type, button_order, id);
