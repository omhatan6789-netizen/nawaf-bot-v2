-- Manually uploaded Telegram photos used by the image quiz.
CREATE TABLE IF NOT EXISTS image_quiz_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id TEXT UNIQUE NOT NULL,
    answer TEXT NOT NULL,
    alternative_answers TEXT NOT NULL DEFAULT '[]'
);
CREATE INDEX IF NOT EXISTS idx_image_quiz_images_file_id
    ON image_quiz_images(file_id);
