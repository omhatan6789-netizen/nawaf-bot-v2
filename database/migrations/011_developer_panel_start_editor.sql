-- Admin tools and start editor tables migrated from the legacy SQLite schema.
-- These tables are created empty; legacy data is not copied by this migration.

CREATE TABLE IF NOT EXISTS developer_panel_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE NOT NULL,
    username TEXT,
    first_name TEXT,
    added_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    added_by BIGINT
);

CREATE TABLE IF NOT EXISTS developer_private_starts (
    user_id BIGINT PRIMARY KEY,
    username TEXT,
    first_name TEXT,
    started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_start_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS developer_bot_chats (
    chat_id BIGINT PRIMARY KEY,
    chat_type TEXT NOT NULL,
    title TEXT,
    username TEXT,
    active SMALLINT DEFAULT 1,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS developer_broadcasts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL,
    sender_name TEXT,
    source_chat_id BIGINT NOT NULL,
    source_message_id BIGINT NOT NULL,
    broadcast_type TEXT NOT NULL,
    pin_enabled SMALLINT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS developer_broadcast_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broadcast_id BIGINT NOT NULL,
    chat_id BIGINT NOT NULL,
    chat_type TEXT NOT NULL,
    title TEXT,
    username TEXT,
    sent_message_id BIGINT,
    success SMALLINT DEFAULT 0,
    error TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS start_settings (
    id INTEGER PRIMARY KEY,
    message_text TEXT DEFAULT '',
    message_entities TEXT DEFAULT '[]'
);

INSERT INTO start_settings (id, message_text, message_entities)
VALUES (1, '', '[]')
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS start_buttons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    button_text TEXT NOT NULL,
    button_url TEXT NOT NULL,
    button_order INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS start_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id TEXT NOT NULL,
    image_order INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS start_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    username TEXT
);

CREATE INDEX IF NOT EXISTS idx_developer_bot_chats_active
    ON developer_bot_chats (active, chat_type);

CREATE INDEX IF NOT EXISTS idx_developer_broadcast_targets_broadcast
    ON developer_broadcast_targets (broadcast_id, id);

CREATE INDEX IF NOT EXISTS idx_start_buttons_order
    ON start_buttons (button_order, id);

CREATE INDEX IF NOT EXISTS idx_start_images_order
    ON start_images (image_order, id);

CREATE INDEX IF NOT EXISTS idx_start_access_user_id
    ON start_access (user_id);
