async def delete_question_by_reply(message, user_id, game_name):
    if not await is_game_admin(user_id, message.chat_id):
        await message.reply_text("هذا الأمر للمشرفين فقط.")
        return
    replied = message.reply_to_message
    if not replied:
        await message.reply_text("رد على رسالة السؤال واكتب:\nحذف اسم اللعبة")
        return
    actual_game = get_matching_game(game_name)
    if not actual_game:
        await message.reply_text("اللعبة غير موجودة.")
        return
    pool = get_pool()
    async with pool.acquire() as conn:
        async with conn.transaction():
            row = await conn.fetchrow(
                "SELECT question_id FROM game_question_messages WHERE chat_id=$1 AND message_id=$2",
                message.chat_id, replied.message_id,
            )
            if not row:
                await message.reply_text("ما لقيت سؤالًا مرتبطًا بالرسالة التي رددت عليها.")
                return
            question_id = row["question_id"]
            question_row = await conn.fetchrow("SELECT game_name FROM game_questions WHERE id=$1", question_id)
            if not question_row:
                await message.reply_text("السؤال غير موجود.")
                return
            if normalize_text(question_row["game_name"]) != normalize_text(actual_game):
                await message.reply_text(f"السؤال الذي رددت عليه ليس من لعبة {actual_game}.")
                return
            await conn.execute("DELETE FROM game_question_messages WHERE question_id=$1", question_id)
            await conn.execute("DELETE FROM game_questions WHERE id=$1", question_id)
    cancel_question_everywhere(question_id)
    cache_key = normalize_text(actual_game)
    cached_questions = _questions_cache.get(cache_key)
    if cached_questions is not None:
        _questions_cache[cache_key] = [item for item in cached_questions if item["id"] != question_id]
    await message.reply_text("تم حذف السؤال وإجاباته بنجاح.")

