async def delete_game(message, user_id, game_name):
    global _games_cache
    if not await is_game_admin(user_id, message.chat_id):
        await message.reply_text("هذا الأمر للمشرفين فقط.")
        return
    actual_name = get_matching_game(game_name)
    if not actual_name:
        await message.reply_text("اللعبة غير موجودة.")
        return
    pool = get_pool()
    async with pool.acquire() as conn:
        async with conn.transaction():
            await conn.execute("""
                DELETE FROM game_question_messages
                WHERE question_id IN (SELECT id FROM game_questions WHERE game_name=$1)
            """, actual_name)
            await conn.execute("DELETE FROM game_questions WHERE game_name=$1", actual_name)
            await conn.execute("DELETE FROM games WHERE name=$1", actual_name)
    cancel_game_everywhere(actual_name)
    if _games_cache_loaded:
        _games_cache = [name for name in _games_cache if normalize_text(name) != normalize_text(actual_name)]
    _questions_cache.pop(normalize_text(actual_name), None)
    await message.reply_text(f"تم حذف لعبة {actual_name} وجميع أسئلتها.")

