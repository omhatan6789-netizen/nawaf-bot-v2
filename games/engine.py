async def ensure_game_tables():
    pool = get_pool()
    defaults = get_default_questions()
    async with pool.acquire() as conn:
        async with conn.transaction():
            await conn.execute("""
                CREATE TABLE IF NOT EXISTS games (
                    name TEXT PRIMARY KEY, image TEXT, status TEXT DEFAULT 'on'
                )
            """)
            await conn.execute("""
                CREATE TABLE IF NOT EXISTS game_questions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    game_name TEXT NOT NULL, question TEXT, image TEXT, caption TEXT, answers TEXT
                )
            """)
            await conn.execute("""
                CREATE TABLE IF NOT EXISTS game_question_messages (
                    chat_id BIGINT NOT NULL, message_id BIGINT NOT NULL,
                    question_id BIGINT NOT NULL, PRIMARY KEY (chat_id, message_id)
                )
            """)
            await conn.execute("CREATE INDEX IF NOT EXISTS idx_game_question_messages_question ON game_question_messages(question_id)")
            await conn.execute("CREATE INDEX IF NOT EXISTS idx_game_questions_game_name ON game_questions(game_name)")
            await conn.executemany(
                "INSERT INTO games(name,status) VALUES($1,'on') ON CONFLICT(name) DO NOTHING",
                [(name,) for name in DEFAULT_GAMES],
            )
            for game_name in DEFAULT_GAMES:
                count = await conn.fetchval("SELECT COUNT(*) FROM game_questions WHERE game_name=$1", game_name)
                if count:
                    continue
                rows = [
                    (item["game"], item["question"], item.get("image"), item.get("caption"),
                     json.dumps(item["answers"], ensure_ascii=False))
                    for item in defaults if item["game"] == game_name
                ]
                if rows:
                    await conn.executemany(
                        "INSERT INTO game_questions(game_name,question,image,caption,answers) VALUES($1,$2,$3,$4,$5)",
                        rows,
                    )
    await load_game_caches()

async def load_game_caches():
    global _games_cache, _games_cache_loaded, _questions_cache
    pool = get_pool()
    async with pool.acquire() as conn:
        game_rows = await conn.fetch("SELECT name FROM games WHERE status='on' ORDER BY name")
        question_rows = await conn.fetch("SELECT id,game_name,question,image,caption,answers FROM game_questions ORDER BY id")
    names = [row["name"] for row in game_rows]
    questions = {normalize_text(name): [] for name in names}
    for row in question_rows:
        try:
            answers = json.loads(row["answers"] or "[]")
        except (TypeError, ValueError):
            answers = []
        if isinstance(answers, str):
            answers = [answers]
        elif not isinstance(answers, list):
            answers = []
        questions.setdefault(normalize_text(row["game_name"]), []).append({
            "id": row["id"], "question": row["question"] or "",
            "image": row["image"], "caption": row["caption"], "answers": answers,
        })
    _games_cache = names
    _games_cache_loaded = True
    _questions_cache = questions

def get_game_questions(game_name, force=False):
    return list(_questions_cache.get(normalize_text(game_name), []))

async def expire_question(chat_id, game_name, question_id, context):
    key = get_game_key(chat_id, game_name)

    try:
        await asyncio.sleep(QUESTION_TIMEOUT)

        active = active_games.get(key)

        if not active or active.get("question_id") != question_id:
            return

        active_games.pop(key, None)
        question_tasks.pop(key, None)

    except asyncio.CancelledError:
        raise

    except Exception as error:
        print(f"خطأ في مؤقت الألعاب: {error}")


