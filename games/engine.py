async def receive_add_question(message, session):
    if message.chat_id != session["chat_id"]:
        return False

    game_name = session["game"]

    if session["stage"] == "question":

        if game_name in ("صور", "شخصيات انمي"):
            if not message.photo:
                await message.reply_text(
                    "هذه اللعبة مخصصة للصور فقط. أرسل صورة."
                )
                return True

        if message.photo:
            session["image"] = message.photo[-1].file_id

            if game_name in ("صور", "شخصيات انمي"):
                session["question"] = ""
                session["caption"] = ""

            else:
                session["question"] = message.caption or ""
                session["caption"] = message.caption or ""

        elif message.text:
            session["question"] = message.text.strip()

        else:
            await message.reply_text("أرسل نصًا أو صورة.")
            return True

        session["stage"] = "answers"

        await message.reply_text(
            "ممتاز! أرسل الإجابات الآن.\n"
            "تقدر ترسل أكثر من إجابة، كل إجابة في سطر مستقل.\n"
            "وبعد الانتهاء أرسل كلمة: تم"
        )

        return True

    if session["stage"] == "answers":

        if not message.text:
            await message.reply_text(
                "أرسل الإجابات كنص، كل إجابة في سطر."
            )
            return True

        text = message.text.strip()

        if normalize_text(text) == "تم":
            answers = list(dict.fromkeys(
                answer.strip()
                for answer in session["answers"]
                if answer.strip()
            ))

            if not answers:
                await message.reply_text(
                    "لم تضف أي إجابة. أرسل الإجابات أولًا."
                )
                return True

            await save_question(message, session, answers)

            add_question_sessions.pop(
                message.from_user.id,
                None
            )

            return True

        new_answers = [
            line.strip()
            for line in text.splitlines()
            if line.strip()
        ]

        session["answers"].extend(new_answers)

        await message.reply_text(
            f"تم استلام {len(new_answers)} إجابة.\n"
            "أرسل إجابات إضافية أو اكتب تم للحفظ."
        )

        return True

    return False


async def save_question(message, session, answers):
    pool = get_pool()
    async with pool.acquire() as conn:
        inserted = await conn.fetchval("""
            INSERT INTO game_questions(game_name,question,image,caption,answers)
            VALUES($1,$2,$3,$4,$5) RETURNING id
        """, session["game"], session["question"], session["image"],
             session["caption"], json.dumps(answers, ensure_ascii=False))
    cache_key = normalize_text(session["game"])
    if inserted and cache_key in _questions_cache:
        _questions_cache[cache_key].append({
            "id": inserted, "question": session["question"] or "",
            "image": session["image"], "caption": session["caption"],
            "answers": list(answers),
        })
    else:
        invalidate_questions_cache(session["game"])
    await message.reply_text(
        f"تمت إضافة السؤال إلى لعبة {session['game']} بنجاح.\n"
        f"عدد الإجابات: {len(answers)}"
    )

